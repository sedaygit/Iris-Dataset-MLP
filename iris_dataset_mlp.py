import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LinearRegression, Ridge, Lasso
from sklearn.neural_network import MLPRegressor
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score, mean_squared_error
from sklearn.model_selection import learning_curve
from sklearn import metrics
from sklearn.tree import plot_tree
from sklearn.svm import SVR
from tensorflow.keras.models import Sequential
from tensorflow.keras import utils as keras_utils
from tensorflow.keras.datasets import fashion_mnist
from tensorflow.keras.utils import to_categorical
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout, SimpleRNN

#Load dataset
iris = load_iris()
X_iris, y_iris = iris.data, iris.target

#Split the dataset for training and testing
X_train_iris, X_test_iris, y_train_iris, y_test_iris = train_test_split(X_iris, y_iris, test_size=0.3,random_state=1)

#Standardize features
scaler = StandardScaler()
X_train_iris = scaler.fit_transform(X_train_iris) #calculates the mean and standard deviation of each feature in the training set and then standardizes the data based on these statistics
X_test_iris = scaler.transform(X_test_iris)

#Initialize and build the MLP_iris model
MLP_Model_iris = Sequential([
    Dense(64, activation='relu', input_shape=(X_train_iris.shape[1],)),
    Dense(128, activation='relu'),
    Dense(256, activation='relu'),
    Dense(512, activation='relu'),
    Dense(3, activation='softmax')
])
#Compile the MLP model
MLP_Model_iris.compile(optimizer=Adam(learning_rate=0.0001), loss='sparse_categorical_crossentropy', metrics=['accuracy'])

#Print the information about MLP model summary
MLP_Model_iris.summary()

#Train the MLP_iris model
MLP_iris=MLP_Model_iris.fit(X_train_iris, y_train_iris, epochs=15, batch_size=1, validation_split=0.3)

# After training is complete, we need to evaluate the model on test data
# to assess the performance of the trained model
test_loss, test_accuracy = MLP_Model_iris.evaluate(X_test_iris, y_test_iris)
print("Test accuracy:", test_accuracy)
print("Test loss: ", test_loss)

#Predictions for the MLP_iris model
MLP_pred = np.argmax(MLP_Model_iris.predict(X_test_iris), axis=1)
for i in range(10):
  print("Test:", i + 1, "-> Predicted:", MLP_pred[i], "Actual class:", y_test_iris[i])

#Evaluation the MLP_iris model
print("MLP_iris Classification Report:\n", classification_report(y_test_iris, MLP_pred))
print("Confusion Matrix:\n", confusion_matrix(y_test_iris, MLP_pred))
print("Accuracy:", accuracy_score(y_test_iris, MLP_pred))

# Plot training and validation accuracy
plt.plot(MLP_iris.history['accuracy'], label='Training Accuracy')
plt.plot(MLP_iris.history['val_accuracy'], label='Validation Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend()
# Plot training and validation loss
plt.plot(MLP_iris.history['loss'], label='Training Loss')
plt.plot(MLP_iris.history['val_loss'], label='Validation Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.title('MLP Loss and Accuracy for Iris Dataset')
plt.legend()
plt.show()